interface I18nContextValue {
  locale: Locale;
  setLocale(locale: Locale): void;
  t(key: string, params?: TranslationParams): string;
}

const fallbackContext: I18nContextValue = {
  locale: "en",
  setLocale: () => {},
  t: (key, params) => translate("en", key, params),
};

const I18nContext = createContext<I18nContextValue>(fallbackContext);

export function I18nProvider({
  children,
  initialLocale: initialLocaleOverride,
}: {
  children: React.ReactNode;
  initialLocale?: Locale;
}) {
  const [locale, setLocaleState] = useState<Locale>(() => initialLocaleOverride ?? initialLocale());

  const setLocale = useCallback((nextLocale: Locale) => {
    setLocaleState(nextLocale);
    if (typeof window !== "undefined") {
      window.localStorage.setItem(LOCALE_STORAGE_KEY, nextLocale);
    }
  }, []);

  useEffect(() => {
    if (typeof window !== "undefined") {
      window.localStorage.setItem(LOCALE_STORAGE_KEY, locale);
    }
  }, [locale]);

  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      setLocale,
      t: (key, params) => translate(locale, key, params),
    }),
    [locale, setLocale],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}

export function translate(locale: Locale, key: string, params: TranslationParams = {}): string {
  const template = TRANSLATIONS[locale][key] ?? TRANSLATIONS.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match,
  );
}

export function initialLocale(storage: Pick<Storage, "getItem"> | undefined = browserStorage()): Locale {
  const storedLocale = storage?.getItem(LOCALE_STORAGE_KEY);
  return isSupportedLocale(storedLocale) ? storedLocale : "en";
}

export function isSupportedLocale(value: unknown): value is Locale {
  return typeof value === "string" && SUPPORTED_LOCALES.includes(value as Locale);
}

function browserStorage(): Pick<Storage, "getItem"> | undefined {
  return typeof window === "undefined" ? undefined : window.localStorage;
}
